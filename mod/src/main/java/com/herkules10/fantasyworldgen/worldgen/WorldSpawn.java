package com.herkules10.fantasyworldgen.worldgen;

import com.herkules10.fantasyworldgen.FantasyWorldgen;
import com.herkules10.fantasyworldgen.engine.TerrainEngine;

import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.data.worldgen.features.MiscOverworldFeatures;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.storage.ServerLevelData;
import net.neoforged.bus.api.EventPriority;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.level.LevelEvent;

/**
 * Puts the initial world spawn where the engine says ({@link TerrainEngine#findSpawn}). Vanilla's spawn search asks the
 * climate sampler of the level's {@code RandomState}, which is a dummy for our generator and knows nothing about the
 * engine's land, so it would spawn players in the sea.
 * <p>
 * Runs at low priority and doesn't receive canceled events, so any listener that already chose a spawn wins: the
 * headless renderer (which keeps the spawn at the origin and generates no spawn chunks), or another mod.
 */
public final class WorldSpawn {
    private WorldSpawn() {}

    public static void register() {
        NeoForge.EVENT_BUS.register(WorldSpawn.class);
    }

    @SubscribeEvent(priority = EventPriority.LOW)
    public static void onCreateSpawnPosition(LevelEvent.CreateSpawnPosition event) {
        if (!(event.getLevel() instanceof ServerLevel level)) return;
        BlockPos pos = spawnPos(level);
        if (pos == null) return;
        ServerLevelData data = event.getSettings();
        data.setSpawn(pos, 0f);
        event.setCanceled(true);
        FantasyWorldgen.LOGGER.info("World spawn at {} ({})", pos.toShortString(), engine(level).biomeAt(pos.getX(), pos.getZ()).id());

        // Canceling skips the rest of vanilla's setup, which includes the bonus chest.
        if (level.getServer().getWorldData().worldGenOptions().generateBonusChest()) {
            level.registryAccess().registry(Registries.CONFIGURED_FEATURE)
                    .flatMap(features -> features.getHolder(MiscOverworldFeatures.BONUS_CHEST))
                    .ifPresent(feature -> feature.value().place(level, level.getChunkSource().getGenerator(), level.random, data.getSpawnPos()));
        }
    }

    /** The engine's spawn for this level, or null if the level isn't generated by the engine. */
    public static BlockPos spawnPos(ServerLevel level) {
        TerrainEngine engine = engine(level);
        if (engine == null) return null;
        TerrainEngine.Spawn spawn = engine.findSpawn();
        return new BlockPos(spawn.x(), spawn.y(), spawn.z());
    }

    private static TerrainEngine engine(ServerLevel level) {
        return level.getChunkSource().getGenerator() instanceof FantasyChunkGenerator generator
                ? generator.engine(level.getChunkSource().randomState())
                : null;
    }
}
